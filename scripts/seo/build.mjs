// Rebuilds the managed SEO head block, JSON-LD graph and listing FAQ for every page in site.config.mjs.
// Idempotent: run it after any copy or listing change.  Usage: node scripts/seo/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { ORIGIN, SITE, PAGES } from './site.config.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const HEAD_START = '<!-- seo:start (generated by scripts/seo/build.mjs, do not edit by hand) -->';
const HEAD_END = '<!-- seo:end -->';
const FAQ_START = '<!-- faq:start (generated) -->';
const FAQ_END = '<!-- faq:end -->';

const abs = (p) => (p.startsWith('http') ? p : ORIGIN + (p.startsWith('/') ? p : '/' + p));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const decode = (s) => s
  .replace(/<[^>]+>/g, '')
  .replace(/&sup2;/g, '²').replace(/&amp;/g, '&').replace(/&bull;/g, '•').replace(/&mdash;/g, '—')
  .replace(/&ndash;/g, '–').replace(/&rsquo;/g, '’').replace(/&nbsp;/g, ' ').replace(/&quot;/g, '"')
  .replace(/\s+/g, ' ').trim();
const num = (n) => n.toLocaleString('en-US', { maximumFractionDigits: 2 });
const zar = (n) => 'R' + num(n);
const listJoin = (a) => (a.length < 2 ? a.join('') : a.slice(0, -1).join(', ') + ' and ' + a[a.length - 1]);
const slug = (p) => (p.path === '/' ? 'home' : p.path.slice(1));
const byFile = Object.fromEntries(PAGES.map((p) => [p.file, p]));

