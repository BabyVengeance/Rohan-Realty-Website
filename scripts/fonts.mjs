// Self-hosts the site's Google Fonts from @fontsource-variable (OFL), latin subset only.
// Removes the third-party request (speed, and no visitor IP sent to Google before consent).
// Usage: node scripts/fonts.mjs  (idempotent)
import fs from 'node:fs';

const OUT = 'assets/fonts';
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const FAMILIES = [
  { name: 'Outfit', pkg: 'outfit', range: '100 900', italic: false },
  { name: 'Inter', pkg: 'inter', range: '100 900', italic: false },
  { name: 'Roboto', pkg: 'roboto', range: '100 900', italic: false },
  { name: 'Playfair Display', pkg: 'playfair-display', range: '400 900', italic: true },
  { name: 'Cormorant Garamond', pkg: 'cormorant-garamond', range: '300 700', italic: true },
];

fs.mkdirSync(OUT, { recursive: true });
let css = '/* Generated by scripts/fonts.mjs. Fonts: SIL Open Font License 1.1 via @fontsource-variable. */\n';
for (const f of FAMILIES) {
  for (const style of f.italic ? ['normal', 'italic'] : ['normal']) {
    const file = `${f.pkg}-latin-wght-${style}.woff2`;
    fs.copyFileSync(`node_modules/@fontsource-variable/${f.pkg}/files/${file}`, `${OUT}/${file}`);
    css += `@font-face{font-family:'${f.name}';font-style:${style};font-display:swap;font-weight:${f.range};src:url(${file}) format('woff2');unicode-range:${LATIN};}\n`;
  }
}
fs.writeFileSync(`${OUT}/fonts.css`, css);

const FONT_LINKS = /[ \t]*<link[^>]+(?:fonts\.googleapis\.com|fonts\.gstatic\.com)[^>]*>\r?\n?/g;
const TAGS = '  <link rel="preload" href="assets/fonts/outfit-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin>\n  <link rel="stylesheet" href="assets/fonts/fonts.css">\n';
for (const file of fs.readdirSync('.').filter((n) => n.endsWith('.html'))) {
  const html = fs.readFileSync(file, 'utf8');
  if (!FONT_LINKS.test(html)) continue;
  FONT_LINKS.lastIndex = 0;
  let first = true;
  const out = html.replace(FONT_LINKS, () => (first ? ((first = false), TAGS) : ''));
  fs.writeFileSync(file, out);
}
